import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { parseEnv } from 'node:util';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../study-log-web/package.json', import.meta.url));
const { chromium, expect } = require('@playwright/test');
const [root, base] = process.argv.slice(2);
if (!root || !path.isAbsolute(root) || !base || !['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw Error('Explicit local synthetic instance required');
const env = parseEnv(await fs.readFile(path.join(root, '.env'), 'utf8'));
const output = path.join(root, 'artifacts', 'availability'); await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  let configured = false;
  await page.route('**/api/capabilities', async route => {
    const response = await route.fetch(); const json = await response.json();
    if (configured && response.ok()) json.features.rag = { supported: true, configured: true };
    await route.fulfill({ response, json });
  });
  await page.goto(base + '?date=2026-01-15');
  await page.getByLabel('访问密码').fill(env.APP_PASSWORD);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.getByRole('button', { name: 'AI生成', exact: true }).filter({ visible: true }).click();
  const notice = page.locator('.writing-panel .feature-availability');
  await expect(notice).toContainText('AI 写作尚未启用');
  await expect(notice.locator('details')).not.toHaveAttribute('open');
  assert.doesNotMatch(await notice.innerText(), /CHAT_API|CHAT_MODEL/);
  await expect(page.getByLabel('学习材料', { exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: '生成日志草稿', exact: true })).toBeDisabled();
  await page.screenshot({ path: path.join(output, 'writing-desktop.png'), animations: 'disabled' });
  await notice.locator('summary').click();
  await expect(notice).toContainText('模型访问密钥');
  await expect(notice.getByRole('button', { name: '重新检查', exact: true })).toBeVisible();
  await notice.getByRole('button', { name: '重新检查', exact: true }).click();
  await expect(page.getByLabel('学习材料', { exact: true })).toBeEnabled();
  await page.locator('.topbar').getByRole('button', { name: '问答', exact: true }).click();
  const rag = page.locator('.rag-composer .feature-availability');
  await expect(rag).toBeVisible();
  const title = await page.locator('.reader-toolbar-qa').boundingBox();
  const header = await page.locator('.topbar').boundingBox();
  assert.ok(Math.abs(title.y - header.y - header.height) < 3, 'no configuration row above module title');
  await expect(page.getByRole('button', { name: '发送问题', exact: true })).toBeDisabled();
  await page.screenshot({ path: path.join(output, 'rag-desktop.png'), animations: 'disabled' });
  await page.getByRole('button', { name: '切换主题模式', exact: true }).click();
  await page.getByRole('button', { name: '夜间模式', exact: true }).click();
  await page.screenshot({ path: path.join(output, 'rag-dark.png'), animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(rag).toBeVisible();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await rag.locator('summary').click();
  await expect(rag.getByRole('button', { name: '重新检查', exact: true })).toBeVisible();
  await rag.locator('summary').click();
  await page.screenshot({ path: path.join(output, 'rag-mobile.png'), animations: 'disabled' });
  configured = true;
  await rag.locator('summary').click();
  await rag.getByRole('button', { name: '重新检查', exact: true }).click();
  await expect(rag).toHaveCount(0);
  await page.getByLabel('输入知识库问题').fill('合成测试问题，不发送');
  await expect(page.getByRole('button', { name: '发送问题', exact: true })).toBeEnabled();
  await page.getByLabel('输入知识库问题').fill('');
  await page.getByRole('button', { name: '日志', exact: true }).filter({ visible: true }).click();
  await page.getByRole('button', { name: '更多设置', exact: true }).click();
  await page.getByRole('button', { name: 'AI 工具', exact: true }).click();
  await expect(notice).toBeVisible();
  if (await notice.locator('details').getAttribute('open') !== null) await notice.locator('summary').click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(output, 'writing-mobile.png'), animations: 'disabled' });
  assert.deepEqual(errors, []);
  console.log('Passed: compact dark availability, readable optional details, disabled AI with usable materials, Q&A title position, mobile fit, configured-state recovery; no model request');
} finally { await browser.close(); }
