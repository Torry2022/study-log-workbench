import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { createRequire } from "node:module";
import { startLauncher } from "./launcher.mjs";
import { DesktopManager } from "./manager.mjs";
const require = createRequire(new URL("../../study-log-web/package.json", import.meta.url));
const { chromium } = require("@playwright/test");
const evidence = path.resolve(process.argv[2] || ".local/desktop-browser");
await fs.mkdir(evidence, { recursive: true });
const synthetic = await fs.mkdtemp(path.join(os.tmpdir(), "study-log-desktop-browser-"));
const packageRoot = path.join(synthetic, "package"); await fs.mkdir(packageRoot);
const launcher = await startLauncher({ packageRoot, manager: new DesktopManager({ packageRoot }), stateRoot: path.join(synthetic, "state"), openBrowser: false,
  assetsRoot: path.resolve("study-log-web/public"), iconFile: path.resolve("study-log-web/app/icon.svg") });
const browser = await chromium.launch({ headless: true });
const passed = [];
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${launcher.origin}/#${launcher.token}`);
  await page.getByText("已停止", { exact: true }).waitFor();
  assert.equal(new URL(page.url()).hash, "");
  await page.getByLabel("资料目录", { exact: true }).fill(path.join(synthetic, "instance"));
  await page.getByLabel("新建实例的访问密码").fill("synthetic-browser-password");
  await page.getByRole("button", { name: "新建实例", exact: true }).click();
  await page.getByText("已创建资料目录", { exact: true }).waitFor();
  assert.equal(await page.getByLabel("新建实例的访问密码").inputValue(), "");
  await page.getByText("模型配置（可选）", { exact: true }).click();
  await page.getByLabel("模型接口地址").fill("https://example.invalid/v1/chat/completions");
  await page.getByLabel("模型名称").fill("synthetic-model");
  await page.getByLabel("API Key", { exact: true }).fill("synthetic-browser-key");
  await page.getByRole("button", { name: "保存模型配置" }).click();
  await page.getByText("已保存 API Key", { exact: true }).waitFor();
  assert.equal(await page.getByLabel("API Key", { exact: true }).inputValue(), "");
  await page.reload(); await page.getByText("已保存 API Key", { exact: true }).waitFor({ state: "attached" });
  await page.evaluate(() => document.fonts.ready);
  assert.equal(await page.evaluate(() => [...document.querySelectorAll(".theme-logo img")].every(image => image.complete && image.naturalWidth > 0)), true);
  assert.equal((await page.request.get(`${launcher.origin}/icon.svg`)).status(), 200);
  const originalRoot = await page.getByLabel("资料目录", { exact: true }).inputValue();
  await page.route("**/api/pick", route => route.fulfill({ contentType: "application/json", body: '{"path":""}' }));
  await page.getByRole("button", { name: "选择目录", exact: true }).click();
  await page.getByText("已取消", { exact: true }).waitFor();
  assert.equal(await page.getByLabel("资料目录", { exact: true }).inputValue(), originalRoot);
  await page.unroute("**/api/pick");
  await page.screenshot({ path: path.join(evidence, "desktop-light.png"), fullPage: true });
  passed.push("Wide UI: create without model, user password, credential clear, saved configuration reload");
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ colorScheme: "dark" });
  await page.getByText("模型配置（可选）", { exact: true }).click();
  await page.getByText("备份与恢复", { exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByLabel("模型名称").fill("中文模型测试");
  assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), "rgb(21, 20, 18)");
  await page.waitForFunction(() => getComputedStyle(document.querySelector(".theme-logo-dark")).opacity === "1");
  assert.equal(await page.locator(".theme-logo-dark").evaluate(image => getComputedStyle(image).opacity), "1");
  await page.screenshot({ path: path.join(evidence, "narrow-dark.png"), fullPage: true });
  assert.deepEqual(errors, []); passed.push("Narrow dark UI: no horizontal overflow, details and controls accessible, no page errors");
  await page.getByRole("button", { name: "退出启动入口" }).click();
  await page.getByText("服务已正常退出，可以关闭此页面。", { exact: true }).waitFor();
  await fs.writeFile(path.join(evidence, "report.json"), JSON.stringify({ passed, limitation: "Launcher-only browser interaction; picker cancellation uses a protocol stub, not native dialog automation. Actual packaged services are covered separately by smoke-package.mjs." }, null, 2));
  console.log(JSON.stringify({ passed, evidence }));
} finally {
  await browser.close(); await launcher.close();
  assert.equal(path.dirname(synthetic), path.resolve(os.tmpdir())); assert.match(path.basename(synthetic), /^study-log-desktop-browser-/);
  await fs.rm(synthetic, { recursive: true, force: true });
}
