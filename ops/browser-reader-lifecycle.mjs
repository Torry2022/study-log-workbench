import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { parseEnv } from 'node:util';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../study-log-web/package.json',import.meta.url));
const {chromium,expect}=require('@playwright/test');
const [root,base='http://127.0.0.1:3561/study-log']=process.argv.slice(2);
if(!root||!path.isAbsolute(root)||!['127.0.0.1','localhost'].includes(new URL(base).hostname))throw Error('Local fixture required');
const env=parseEnv(await fs.readFile(path.join(root,'.env'),'utf8'));
const browser=await chromium.launch({headless:true});
try{
 const page=await browser.newPage({viewport:{width:1100,height:900}});
 await page.goto(base+'?date=2026-01-15');
 await page.getByLabel('访问密码').fill(env.APP_PASSWORD);await page.getByRole('button',{name:'登录',exact:true}).click();
 await expect(page.locator('.markdown-preview')).toContainText('同名小节',{timeout:60000});
 await page.getByRole('button',{name:'进入阅读模式',exact:true}).click();
 await page.getByRole('button',{name:'打开日志大纲',exact:true}).filter({visible:true}).click();
 await expect(page.getByRole('dialog',{name:'当前日志大纲'})).toBeVisible(); await page.keyboard.press('Escape');
 await expect(page.getByRole('dialog',{name:'当前日志大纲'})).not.toBeVisible();
 await page.getByRole('button',{name:'退出阅读',exact:true}).click();
 let release,started;
 const gate=new Promise(r=>release=r);const requested=new Promise(r=>started=r);
 await page.route('**/api/logs/day?date=2026-01-17',async route=>{const response=await route.fetch();started();await gate;await route.fulfill({response}).catch(()=>{});});
 await page.locator('.day-item-open').filter({hasText:'01-17'}).click();await requested;
 await page.locator('.day-item-open').filter({hasText:'01-15'}).click();
 await expect(page.locator('.markdown-preview')).toContainText('同名小节');release();
 await expect(page.locator('.reader-log-identity h2')).toHaveText('2026-01-15');
 await page.unroute('**/api/logs/day?date=2026-01-17');
 let fail=true;
 await page.route('**/api/logs/day?date=2026-01-17',route=>fail?route.fulfill({status:503,json:{error:'合成读取故障'}}):route.continue());
 await page.locator('.day-item-open').filter({hasText:'01-17'}).click();
 await expect(page.locator('.preview-empty[role=alert]')).toContainText('合成读取故障');
 fail=false;await page.locator('.preview-empty').getByRole('button',{name:'重新加载',exact:true}).click();await expect(page.locator('.markdown-preview')).toContainText('文件版本');
 await page.unroute('**/api/logs/day?date=2026-01-17');
 let expire=true;
 await page.route('**/api/logs/day?date=2026-01-15',route=>expire?route.fulfill({status:401,json:{error:'Unauthorized'}}):route.continue());
 await page.locator('.day-item-open').filter({hasText:'01-15'}).click();
 await expect(page.getByRole('button',{name:'登录',exact:true})).toBeVisible();
 await expect(page.locator('.reader')).toBeHidden();expire=false;
 await page.getByLabel('访问密码').fill(env.APP_PASSWORD);await page.getByRole('button',{name:'登录',exact:true}).click();
 await expect(page.locator('.markdown-preview')).toContainText('同名小节');
 await page.goto(base+'?date=2026-01-16');await expect(page.locator('.preview-empty')).toContainText('暂无正文');
 await page.goto(base+'?month=2026-03');await expect(page.locator('.day-empty')).toContainText('本月暂无日志');
 await page.getByRole('button',{name:'退出',exact:true}).click();await expect(page.getByRole('button',{name:'登录',exact:true})).toBeVisible();
 assert.equal(await page.locator('.reader').count(),0);
 console.log('Passed: medium-width outline, delayed navigation, retry, authentication expiry/relogin, missing day/month, explicit logout cleanup');
}finally{await browser.close();}
